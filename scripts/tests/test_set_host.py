"""set_host clears the dev database only when a switch moves what stored photo
URLs are built from. On 2026-10-30 re-applying the live profile to re-render one
setting wiped a restored prod dump; re-applying must keep the data."""
import importlib.util
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))  # set_host imports host_profiles from beside it
spec = importlib.util.spec_from_file_location('set_host', SCRIPTS / 'set_host.py')
set_host = importlib.util.module_from_spec(spec)
spec.loader.exec_module(set_host)

POOLS = '[{"type":"files","path":"/app/pics","url":"https://hv.example/pics/"}]'
BASE = f"""POSTGRES_DB=hillview
# >>> set_host: box-ygg — generated by scripts/set_host.py, edits here are overwritten
PICS_URL=https://hv.example/pics/
WORKER_URL=https://hv.example/worker
FILE_POOLS={POOLS}
# <<< set_host
"""


def test_reapplying_the_live_profile_keeps_the_data():
	extra = BASE.replace('WORKER_URL=', 'PANORAMAX_VIEWER_URL=https://hv.example\nWORKER_URL=')
	assert not set_host.photo_urls_move(BASE, BASE)
	assert not set_host.photo_urls_move(BASE, extra)


def test_moving_pics_url_or_a_pool_url_clears():
	assert set_host.photo_urls_move(BASE, BASE.replace('PICS_URL=https://hv.example/pics/', 'PICS_URL=http://10.0.0.1:9999/'))
	assert set_host.photo_urls_move(BASE, BASE.replace('"url":"https://hv.example/pics/"', '"url":"http://10.0.0.1:9999/"'))


def test_a_first_render_clears():
	# No block yet: rows were written under whatever the base file declared.
	assert set_host.photo_urls_move('POSTGRES_DB=hillview\n', BASE)
